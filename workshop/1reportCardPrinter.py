# Signing a variable
name = 'Alice';

# Print a variable value in the terminal using print() function
greeting = 'Hello World'
print(greeting) # Output: Hello World
print(name) # Output: Alice

# Check the type value of the variable with type()
type(name)
print(type(name)) # Print the output type in the terminal

# Boolean values to check wether its True or False
is_student = True

# Print multiple value with one function print()
subject = 'Python'
print(subject, type(subject)) # Output: Python <class 'str'>

print(name, type(name))
print(is_student, type(is_student))


# Integer value
age = 20
print(age, type(age))

# isinstance() function
x = 10
print(isinstance(x, int)) # Output: True

score = 80.5
print(isinstance(score, int))
print(isinstance(score, float))
print(score, type(score))


